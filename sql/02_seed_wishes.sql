-- 테스트 계정의 이메일을 아래 한 곳에만 바꿔서 실행
-- (user_id를 직접 복사해 붙이지 않아도 되도록 auth.users에서 찾아서 넣음)
INSERT INTO public.wishes (user_id, title)
SELECT u.id, t.title
FROM auth.users u,
     unnest(ARRAY[
       '제주도에서 일주일 동안 한 달 살기 체험하기',
       '자격증 하나 따서 이력서에 한 줄 추가하기',
       '새벽 해돋이 보러 강릉까지 기차 타고 가기',
       '운동 시작해서 방학이 끝나기 전에 5km 완주하기',
       '미뤄둔 책 세 권 끝까지 읽기',
       '친구들이랑 1박 2일로 캠핑 다녀오기',
       '요리 하나 제대로 배워서 가족한테 대접하기',
       '밀린 드라마와 영화 몰아보기',
       '아르바이트로 모은 돈으로 갖고 싶던 키보드 사기',
       '늦잠 자고 일어나서 아무 계획 없는 하루 보내기'
     ]) AS t(title)
WHERE u.email = '여기에-테스트-계정-이메일';
